#!/usr/bin/env node
// Cross-checks `spikes/binary64-oracle/vectors.json` against:
//   1. Fork #23's `math-special-values.json` (`--math-vectors <path>`), verifying 100%
//      agreement on every overlapping `(member, inputs)` tuple's `{ js, hex, class }`.
//   2. Fork #20's Dafny Encoding B library (`--dafny-spike <dir>`), emitting Dafny lemmas
//      against `corpus/B_lib.dfy` for overlapping exact operations (`MathMin`, `MathMax`,
//      `MathTrunc`, `MathRound`, `StrictEq`, `ObjectIs`, `SameValueZero`, `Lt`, `Truthy`,
//      `Neg`) and verifying them with `dafny verify`.
//
// Usage:
//   node spikes/binary64-oracle/crosscheck-dafny.mjs \
//     [--vectors spikes/binary64-oracle/vectors.json] \
//     [--math-vectors /path/to/spikes/math-semantics/vectors/math-special-values.json] \
//     [--dafny-spike /path/to/spikes/dafny-number-encodings] \
//     [--dafny dafny]

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

function argValue(flag, fallback = null) {
  const idx = process.argv.indexOf(flag);
  return idx >= 0 && process.argv[idx + 1] ? process.argv[idx + 1] : fallback;
}

const vectorsPath = resolve(argValue('--vectors', join(here, 'vectors.json')));
const mathVectorsPath = argValue('--math-vectors');
const dafnySpikeDir = argValue('--dafny-spike');
const dafnyBin = argValue('--dafny', process.env.DAFNY || 'dafny');

if (!mathVectorsPath && !dafnySpikeDir) {
  console.error(
    'Usage: node spikes/binary64-oracle/crosscheck-dafny.mjs [--math-vectors <file>] [--dafny-spike <dir>] [--dafny <bin>]',
  );
  process.exit(2);
}

const oracle = JSON.parse(readFileSync(vectorsPath, 'utf8'));

if (mathVectorsPath) {
  const mathDoc = JSON.parse(readFileSync(resolve(mathVectorsPath), 'utf8'));
  const index = new Map();
  for (const r of mathDoc.records) {
    const key = `${r.member}(${r.inputs.map((x) => x.hex).join(',')})`;
    index.set(key, r);
  }
  let matched = 0;
  let mismatches = 0;
  for (const r of oracle.records) {
    if (r.family !== 'math-deterministic') continue;
    const key = `${r.member}(${r.inputs.map((x) => x.hex).join(',')})`;
    const other = index.get(key);
    if (!other) continue;
    matched++;
    if (other.result.hex !== r.result.hex || other.result.js !== r.result.js || other.class !== r.class) {
      mismatches++;
      console.error(`MISMATCH ${key}: oracle=${JSON.stringify(r.result)} vs #23=${JSON.stringify(other.result)}`);
    }
  }
  console.log(`math-vectors cross-check: ${matched} overlapping records checked, ${mismatches} mismatches`);
  if (matched === 0 || mismatches > 0) process.exit(1);
}

// Exact decimal expansion of a finite, positive binary64 bit pattern (mirrors fork #20's gen-dfy.mjs).
function exactDecimal(bits) {
  const expBits = Number((bits >> 52n) & 0x7ffn);
  const frac = bits & ((1n << 52n) - 1n);
  const mant = expBits === 0 ? frac : frac | (1n << 52n);
  const e = (expBits === 0 ? 1 : expBits) - 1075;
  if (e >= 0) return `${mant << BigInt(e)}.0`;
  const places = -e;
  const digits = (mant * 5n ** BigInt(places)).toString().padStart(places + 1, '0');
  const intPart = digits.slice(0, digits.length - places);
  const fracPart = digits.slice(digits.length - places).replace(/0+$/, '');
  return `${intPart}.${fracPart || '0'}`;
}

function toEncodingB(v) {
  const bits = BigInt(v.hex);
  const neg = bits >> 63n === 1n;
  const mag = bits & ((1n << 63n) - 1n);
  if (mag === 0x7ff0000000000000n) return neg ? 'NegInf' : 'PosInf';
  if (mag > 0x7ff0000000000000n) return 'NaN';
  if (mag === 0n) return neg ? 'NegZero' : 'PosZero';
  return `Lit(${neg ? '-' : ''}${exactDecimal(mag)})`;
}

if (dafnySpikeDir) {
  const bLibPath = resolve(dafnySpikeDir, 'corpus/B_lib.dfy');
  const lines = [
    `include "${bLibPath.replace(/\\/g, '\\\\')}"`,
    `// Generated by spikes/binary64-oracle/crosscheck-dafny.mjs from ${oracle.schema}`,
    '',
  ];
  let count = 0;

  // 1. Sampled Math.min, Math.max, Math.trunc, Math.round records
  const mathMap = [
    { member: 'Math.min', fn: 'MathMin', arity: 2, step: 6 },
    { member: 'Math.max', fn: 'MathMax', arity: 2, step: 6 },
    { member: 'Math.trunc', fn: 'MathTrunc', arity: 1, step: 2 },
    { member: 'Math.round', fn: 'MathRound', arity: 1, step: 2 },
  ];
  for (const { member, fn, arity, step } of mathMap) {
    const recs = oracle.records.filter(
      (r) => r.family === 'math-deterministic' && r.member === member && r.inputs.length === arity,
    );
    recs.forEach((r, i) => {
      if (i % step !== 0) return;
      const args = r.inputs.map(toEncodingB).join(', ');
      lines.push(`lemma Oracle_${fn}_${count++}() ensures ObjectIs(${fn}(${args}), ${toEncodingB(r.result)}) {}`);
    });
  }

  // 2. Sampled unary negation, truthiness, and equality/comparison records
  const unaryNeg = oracle.records.filter((r) => r.family === 'unary-arithmetic' && r.op === 'unary-');
  unaryNeg.forEach((r, i) => {
    if (i % 4 !== 0) return;
    lines.push(
      `lemma Oracle_Neg_${count++}() ensures ObjectIs(Neg(${toEncodingB(r.inputs[0])}), ${toEncodingB(r.result)}) {}`,
    );
  });

  const truthy = oracle.records.filter((r) => r.family === 'truthiness');
  truthy.forEach((r, i) => {
    if (i % 4 !== 0) return;
    const expected = r.result.bool ? 'true' : 'false';
    lines.push(`lemma Oracle_Truthy_${count++}() ensures Truthy(${toEncodingB(r.inputs[0])}) == ${expected} {}`);
  });

  const cmp = oracle.records.filter((r) => r.family === 'comparison-equality');
  cmp.forEach((r, i) => {
    if (i % 6 !== 0) return;
    const a = toEncodingB(r.inputs[0]);
    const b = toEncodingB(r.inputs[1]);
    lines.push(
      `lemma Oracle_Cmp_${count++}() ensures Lt(${a}, ${b}) == ${r.results.lt} && StrictEq(${a}, ${b}) == ${r.results.strictEq} && ObjectIs(${a}, ${b}) == ${r.results.objectIs} && SameValueZero(${a}, ${b}) == ${r.results.sameValueZero} {}`,
    );
  });

  const tmpDir = mkdtempSync(join(tmpdir(), 'lsc-oracle-dafny-'));
  try {
    const dfyFile = join(tmpDir, 'oracle_crosscheck_B.dfy');
    writeFileSync(dfyFile, lines.join('\n') + '\n');
    const res = spawnSync(dafnyBin, ['verify', '--verification-time-limit=30', dfyFile], {
      encoding: 'utf8',
      timeout: 180_000,
    });
    if (res.error) throw res.error;
    const output = (res.stdout + res.stderr).trim();
    console.log(`dafny Encoding B cross-check (${count} lemmas): exit=${res.status}`);
    console.log(output.split('\n').slice(-5).join('\n'));
    if (res.status !== 0) process.exit(res.status ?? 1);
  } finally {
    rmSync(tmpDir, { recursive: true, force: true });
  }
}
