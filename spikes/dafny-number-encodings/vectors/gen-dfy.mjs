// Turns a sample of the fork #23 Math vectors into one Dafny lemma per
// vector for Encoding B and Encoding C.
//
//   node gen-dfy.mjs <math-special-values.json> <out-dir>
//
// Writes <out-dir>/B_vectors.dfy and <out-dir>/C_vectors.dfy. Each lemma
// states ObjectIs(<Math call>, <expected>), so -0 and NaN must match exactly.
// Number values are written as the exact decimal expansion of the binary64
// bit pattern from the vector's "hex" field, so Encoding B sees the same real
// the double holds, and Encoding C gets a literal that is exactly
// representable (no `~` rounding).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const [, , vectorsPath, outDir] = process.argv;
const data = JSON.parse(readFileSync(vectorsPath, 'utf8'));

// Every `step`-th record of each member with the given arity, in file order.
// The library functions are binary MathMin/MathMax and unary
// MathTrunc/MathRound, so variadic min/max records are skipped.
const SAMPLE = [
  { member: 'Math.min', fn: 'MathMin', arity: 2, step: 8 },
  { member: 'Math.max', fn: 'MathMax', arity: 2, step: 8 },
  { member: 'Math.trunc', fn: 'MathTrunc', arity: 1, step: 2 },
  { member: 'Math.round', fn: 'MathRound', arity: 1, step: 2 },
];

// Exact decimal string of a finite, positive binary64 magnitude given by its
// bits, with at least one digit after the point.
function exactDecimal(bits) {
  const expBits = Number((bits >> 52n) & 0x7ffn);
  const frac = bits & ((1n << 52n) - 1n);
  const mant = expBits === 0 ? frac : frac | (1n << 52n);
  const e = (expBits === 0 ? 1 : expBits) - 1075;
  if (e >= 0) return `${mant << BigInt(e)}.0`;
  const places = -e;
  const digits = (mant * 5n ** BigInt(places)).toString().padStart(places + 1, '0');
  const intPart = digits.slice(0, digits.length - places);
  const fracPart = digits.slice(digits.length - places).replace(/0+$/, '');
  return `${intPart}.${fracPart || '0'}`;
}

function classify(hex) {
  const bits = BigInt(hex);
  const neg = bits >> 63n === 1n;
  const mag = bits & ((1n << 63n) - 1n);
  if (mag === 0x7ff0000000000000n) return { kind: 'inf', neg };
  if (mag > 0x7ff0000000000000n) return { kind: 'nan' };
  if (mag === 0n) return { kind: 'zero', neg };
  return { kind: 'finite', neg, dec: exactDecimal(mag) };
}

function toB(v) {
  const c = classify(v.hex);
  switch (c.kind) {
    case 'nan':
      return 'NaN';
    case 'inf':
      return c.neg ? 'NegInf' : 'PosInf';
    case 'zero':
      return c.neg ? 'NegZero' : 'PosZero';
    default:
      return `Lit(${c.neg ? '-' : ''}${c.dec})`;
  }
}

function toC(v) {
  const c = classify(v.hex);
  switch (c.kind) {
    case 'nan':
      return 'fp64.NaN';
    case 'inf':
      return c.neg ? 'fp64.NegativeInfinity' : 'fp64.PositiveInfinity';
    case 'zero':
      return c.neg ? 'fp64.Neg(0.0)' : '0.0';
    default:
      return c.neg ? `fp64.Neg(${c.dec})` : c.dec;
  }
}

function emit(enc, lit) {
  const lines = [
    `// Generated by vectors/gen-dfy.mjs from ${data.schema} (node ${data.engine.node}).`,
    `// Encoding ${enc}. Library: corpus/${enc}_lib.dfy. One lemma per vector.`,
    '',
  ];
  for (const { member, fn, arity, step } of SAMPLE) {
    const recs = data.records.filter((r) => r.member === member && r.inputs.length === arity);
    recs.forEach((r, i) => {
      if (i % step !== 0) return;
      const args = r.inputs.map(lit).join(', ');
      const name = `${fn}_${String(i).padStart(3, '0')}`;
      lines.push(`// ${member}(${r.inputs.map((x) => x.js).join(', ')}) === ${r.result.js} [${r.class}]`);
      lines.push(`lemma ${name}() ensures ObjectIs(${fn}(${args}), ${lit(r.result)}) {}`);
    });
  }
  writeFileSync(join(outDir, `${enc}_vectors.dfy`), lines.join('\n') + '\n');
}

mkdirSync(outDir, { recursive: true });
emit('B', toB);
emit('C', toC);
